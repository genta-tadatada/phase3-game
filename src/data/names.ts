// 略称用の姓のみでよいが、選手名は姓+名で生成
const NG_WORDS = ['死', '殺', '糞', 'クソ', 'バカ', '阿呆']

export function isAppropriateName(name: string): boolean {
  return !NG_WORDS.some((w) => name.includes(w))
}

/** ランダムな選手氏名（姓+名）を生成 */
export function generateName(rng: RNG): string {
  for (let i = 0; i < 5; i++) {
    const name = rng.pick(SURNAMES) + rng.pick(GIVEN_NAMES)
    if (isAppropriateName(name)) return name
  }
  return rng.pick(SURNAMES) + rng.pick(GIVEN_NAMES)
}
