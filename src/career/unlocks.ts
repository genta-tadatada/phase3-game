// 年2開始時に解放されるもの（#18/#38）。年2の早い週に、説明付き解放イベントを1対1で発火する。
// 特にスカウトは攻略の根幹なので最初に解禁を物語る。すべて年2のみ・一度きり。
// 4月1〜2週は卒業/新入生の節目で情報過多になるため、解放は3週目以降にずらす。
const YEAR2_WEEK: Partial<Record<Feature, number>> = {
  scouting: 5,         // G-41 §3: スカウト主任が雇える週(week5)と一致。スカウト機能本体は「スカウト主任雇用」必須にする方針
  events: 5,           // 週次イベントが本格化
}

/** その機能が解放済みか（year, week から導出）。基本機能(練習)は常時可。 */
export function featureUnlocked(f: Feature, year: number, week: number): boolean {
  if (year >= 3) return true
  // G-16: 年2解放機能(scouting/events)は解放週=チュートリアル発火週まではロック。
  //        それ以前に機能だけ使えてしまう「チュートリアル前に解放」を防ぐ。年1で解放済みの機能は年2では常時可。
  if (year === 2) {
    const w2 = YEAR2_WEEK[f]
    return w2 === undefined ? true : week >= w2
  }
  const w = YEAR1_WEEK[f]
  if (w === undefined) return false // 年2以降に解放する機能は年1ではロック
  return week >= w
}

/** その週に新しく解放される機能（解放イベント表示用）。複数同時もあり得る。 */
export function featuresUnlockedAtWeek(year: number, week: number): Feature[] {
  if (year === 1) return (Object.keys(YEAR1_WEEK) as Feature[]).filter((f) => YEAR1_WEEK[f] === week)
  // #18/#38: 年2の解放イベントも1対1で発火（旧実装は year≠1 で空＝スカウト等が無言で解禁されていた）。
  if (year === 2) return (Object.keys(YEAR2_WEEK) as Feature[]).filter((f) => YEAR2_WEEK[f] === week)
  return []
}

